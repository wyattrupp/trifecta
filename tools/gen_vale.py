"""Generate the Vale term rule from the glossary, so the glossary is the only term list."""

from __future__ import annotations

import json
from pathlib import Path


def generate(needs: dict[str, dict], style_dir: Path) -> Path:
    swap = {}
    for need in sorted(needs.values(), key=lambda n: n["id"]):
        if need["type"] != "term" or not need.get("synonyms"):
            continue
        for synonym in need["synonyms"].split(","):
            if synonym.strip():
                swap[synonym.strip()] = need["title"].lower()
    style_dir.mkdir(parents=True, exist_ok=True)
    rule = style_dir / "REQ_CANONICAL_TERMS.yml"
    for stale in style_dir.glob("*.yml"):
        stale.unlink()
    if swap:
        lines = [
            "# Generated by tools/gen_vale.py from the term needs. Do not edit.",
            "extends: substitution",
            "message: \"REQ_CANONICAL_TERMS: use '%s' instead of '%s'\"",
            "level: error",
            "ignorecase: true",
            "swap:",
        ] + [f"  {json.dumps(k)}: {json.dumps(v)}" for k, v in sorted(swap.items())]
        rule.write_text("\n".join(lines) + "\n")
    return rule
