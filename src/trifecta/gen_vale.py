"""Generate the Vale term rule from the glossary, so the glossary is the only term list."""

from __future__ import annotations

import json
import re
from pathlib import Path

from .findings import Finding


def generate(needs: dict[str, dict], style_dir: Path) -> list[Finding]:
    """Write the REQ_CANONICAL_TERMS rule; report synonyms claimed by two terms."""
    swap: dict[str, tuple[str, str]] = {}  # synonym (lowercase) -> (term id, canonical)
    findings = []
    for need in sorted(needs.values(), key=lambda n: n["id"]):
        if need["type"] != "term" or not need.get("synonyms"):
            continue
        for synonym in (s.strip() for s in need["synonyms"].split(",")):
            if not synonym:
                continue
            key = synonym.lower()
            if key in swap and swap[key][0] != need["id"]:
                findings.append(Finding(
                    "REQ_CANONICAL_TERMS", f"need:{need['id']}",
                    f"synonym '{synonym}' is also claimed by {swap[key][0]}",
                ))
                continue
            swap[key] = (need["id"], need["title"].lower())
    style_dir.mkdir(parents=True, exist_ok=True)
    for stale in style_dir.glob("*.yml"):
        stale.unlink()
    if swap:
        # Vale reads swap keys as regular expressions; synonyms are literal words.
        lines = [
            "# Generated by trifecta.gen_vale from the term needs. Do not edit.",
            "extends: substitution",
            "message: \"REQ_CANONICAL_TERMS: use '%s' instead of '%s'\"",
            "level: error",
            "ignorecase: true",
            "swap:",
        ] + [f"  {json.dumps(re.escape(k))}: {json.dumps(v)}" for k, (_, v) in sorted(swap.items())]
        (style_dir / "REQ_CANONICAL_TERMS.yml").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return findings
